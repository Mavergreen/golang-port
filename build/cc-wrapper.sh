#!/bin/sh
# platform: host-agnostic
# spec: PORT.md, the build chain -- build/cc-wrapper.sh: the one flag list every Mavergreen clang wrapper adds, for the build wrapper
#       (c-toolchain.sh) and the shipped ones (write-wrappers.sh). Sourced, not executed; needs MACOS_MIN and WLU_SYMS (env.sh).
#       cc_wrapper OUT PRELUDE writes OUT, an executable sh script. PRELUDE is sh text that sets cc_prefix (a clang22 prefix),
#       sdk (a MacOSX10.9.sdk), recaulk (a librecaulk.a), and no_clang / no_sdk: what to print when that compiler or SDK is absent.
# spec: PORT.md, the build chain -- every call targets x86_64 10.9 against the 10.9 SDK; link steps (no -c/-E/-S) also use lld and
#       Recaulk, and leave the one symbol the 10.9 libSystem lacks to the runtime.
cc_wrapper() {
  _cw_wlu=""
  for _cw_s in $WLU_SYMS; do _cw_wlu="$_cw_wlu -Wl,-U,$_cw_s"; done
  {
    echo '#!/bin/sh'
    echo '# spec: generated by build/cc-wrapper.sh in the Mavergreen golang port; do not edit'
    printf '%s\n' "$2"
    echo '[ -x "$cc_prefix/bin/clang" ] || { echo "${0##*/}: $no_clang" >&2; exit 1; }'
    echo '[ -d "$sdk" ] || { echo "${0##*/}: $no_sdk" >&2; exit 1; }'
    echo 'link=yes'
    echo 'for a in "$@"; do'
    echo '  case "$a" in -c|-E|-S) link=no ;; esac'
    echo 'done'
    printf 'base="-no-canonical-prefixes --no-default-config --target=x86_64-apple-macos%s -isysroot $sdk -mmacosx-version-min=%s"\n' "$MACOS_MIN" "$MACOS_MIN"
    echo 'if [ "$link" = yes ]; then'
    printf '  exec "$cc_prefix/bin/clang" $base -fuse-ld=lld --ld-path="$cc_prefix/bin/ld64.lld" "$@" "$recaulk"%s\n' "$_cw_wlu"
    echo 'fi'
    echo 'exec "$cc_prefix/bin/clang" $base "$@"'
  } > "$1" || return 1
  chmod 755 "$1"
}
